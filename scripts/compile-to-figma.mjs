#!/usr/bin/env node
/**
 * Phase 2: Compile measured DOM JSON into compact, chunked Figma Plugin scripts (<46 KB each).
 *
 * Usage:
 *   node scripts/compile-to-figma.mjs <measured.json> <out.js> [startY] [--page <pageId>]
 *   node scripts/compile-to-figma.mjs --self-test
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

export function buildScriptForSubset(subsetObj, pageId = '52:2') {
  const svgList = [];
  const svgMap = new Map();
  const strList = [];
  const strMap = new Map();

  function intern(val) {
    if (!val) return -1;
    let idx = strMap.get(val);
    if (idx === undefined) {
      idx = strList.length;
      strList.push(val);
      strMap.set(val, idx);
    }
    return idx;
  }

  function internSvg(val) {
    if (!val) return -1;
    let idx = svgMap.get(val);
    if (idx === undefined) {
      idx = svgList.length;
      svgList.push(val);
      svgMap.set(val, idx);
    }
    return idx;
  }

  function encodeBorder(b) {
    if (!b) return 0;
    const st = b.style === 'dashed' ? 1 : b.style === 'dotted' ? 2 : 0;
    return [b.w, st, intern(b.color)];
  }

  function encodeFontCode(ff, weight, fstyle) {
    const f = (ff || '').toLowerCase();
    const w = weight || 400;
    const it = fstyle === 'italic' ? 1 : 0;
    if (f.includes('instrument serif')) return it ? 'Si' : 'Sr';
    if (f.includes('jetbrains mono') || f.includes('mono')) {
      return w >= 600 ? 'Ms' : w >= 500 ? 'Mm' : 'Mr';
    }
    const prefix = f.includes('inter tight') ? 'T' : 'I';
    if (it) return prefix + 'i';
    if (w >= 700) return prefix + 'b';
    if (w >= 600) return prefix + 's';
    if (w >= 500) return prefix + 'm';
    return prefix + 'r';
  }

  const compactData = {};
  for (const [compName, compInfo] of Object.entries(subsetObj)) {
    const stories = {};
    for (const [sName, sData] of Object.entries(compInfo.stories || {})) {
      const items = [];
      for (const it of sData.items || []) {
        const [x, y, w, h] = it.rect || [0, 0, 0, 0];
        if (it.kind === 'box') {
          const rad = it.radius
            ? it.radius[0] === it.radius[1] && it.radius[1] === it.radius[2] && it.radius[2] === it.radius[3]
              ? it.radius[0]
              : it.radius
            : 0;
          items.push([
            0,
            x,
            y,
            w,
            h,
            intern(it.bg),
            encodeBorder(it.bt),
            encodeBorder(it.br),
            encodeBorder(it.bb),
            encodeBorder(it.bl),
            rad,
            intern(it.shadow),
            it.opacity ?? 1,
          ]);
        } else if (it.kind === 'svg' && it.svg) {
          items.push([1, x, y, w, h, internSvg(it.svg), it.opacity ?? 1]);
        } else if (it.kind === 'text' && it.text) {
          const fCode = encodeFontCode(it.fontFamily, it.fontWeight, it.fontStyle);
          const lh =
            it.lineHeight && typeof it.lineHeight === 'string' && it.lineHeight.endsWith('px')
              ? Math.round(parseFloat(it.lineHeight) * 100) / 100
              : 0;
          const ls =
            it.letterSpacing && typeof it.letterSpacing === 'string' && it.letterSpacing.endsWith('px')
              ? Math.round(parseFloat(it.letterSpacing) * 100) / 100
              : 0;
          const flags =
            (it.textTransform === 'uppercase' ? 1 : 0) |
            (it.textDecoration && it.textDecoration.includes('underline') ? 2 : 0);
          items.push([
            2,
            x,
            y,
            w,
            h,
            it.text,
            fCode,
            it.fontSize || 16,
            lh,
            ls,
            intern(it.color || 'rgb(22, 20, 15)'),
            flags,
            it.opacity ?? 1,
            it.lineCount || 1,
          ]);
        }
      }
      stories[sName] = [sData.rootRect, items];
    }
    compactData[compName] = [
      compInfo.title,
      stories,
      Boolean(compInfo.append),
      compInfo.allStoryNames || Object.keys(stories),
    ];
  }

  return `// Auto-generated by compile-to-figma.mjs
const page = await figma.getNodeByIdAsync(${JSON.stringify(pageId)});
if (!page) throw new Error("Target page not found");
await figma.setCurrentPageAsync(page);

const fontsToLoad = [
  { family: "Inter", style: "Regular" },
  { family: "Inter", style: "Medium" },
  { family: "Inter", style: "Semi Bold" },
  { family: "Inter", style: "Bold" },
  { family: "Inter", style: "Italic" },
  { family: "Instrument Serif", style: "Regular" },
  { family: "Instrument Serif", style: "Italic" },
  { family: "JetBrains Mono", style: "Regular" },
  { family: "JetBrains Mono", style: "Medium" },
  { family: "JetBrains Mono", style: "Bold" }
];
const loadedFontKeys = new Set();
for (const f of fontsToLoad) {
  try {
    await figma.loadFontAsync(f);
    loadedFontKeys.add(f.family + "::" + f.style);
  } catch {}
}

const STRS = ${JSON.stringify(strList)};
const SVGS = ${JSON.stringify(svgList)};
const DATA = ${JSON.stringify(compactData)};

function parseColor(str) {
  if (!str) return { color: { r: 0.086, g: 0.078, b: 0.059 }, opacity: 1 };
  const m = str.match(/rgba?\\(\\s*([\\d.]+)\\s*,\\s*([\\d.]+)\\s*,\\s*([\\d.]+)(?:\\s*,\\s*([\\d.]+))?\\s*\\)/i);
  if (!m) return { color: { r: 0.086, g: 0.078, b: 0.059 }, opacity: 1 };
  return {
    color: {
      r: Math.min(1, Math.max(0, parseFloat(m[1]) / 255)),
      g: Math.min(1, Math.max(0, parseFloat(m[2]) / 255)),
      b: Math.min(1, Math.max(0, parseFloat(m[3]) / 255))
    },
    opacity: m[4] !== undefined ? Math.min(1, Math.max(0, parseFloat(m[4]))) : 1
  };
}

function solidPaint(str) {
  const { color, opacity } = parseColor(str);
  return { type: "SOLID", color, opacity };
}

function parseShadows(shadowStr) {
  if (!shadowStr || shadowStr === "none") return [];
  const effects = [];
  const re = /(rgba?\\([^)]+\\))\\s+(-?[\\d.]+)px\\s+(-?[\\d.]+)px\\s+(-?[\\d.]+)px(?:\\s+(-?[\\d.]+)px)?/g;
  let m;
  while ((m = re.exec(shadowStr)) !== null) {
    const { color, opacity } = parseColor(m[1]);
    effects.push({
      type: "DROP_SHADOW",
      color: { r: color.r, g: color.g, b: color.b, a: opacity },
      offset: { x: parseFloat(m[2]) || 0, y: parseFloat(m[3]) || 0 },
      radius: Math.max(0, parseFloat(m[4]) || 0),
      spread: parseFloat(m[5]) || 0,
      visible: true,
      blendMode: "NORMAL"
    });
  }
  return effects;
}

const FONT_MAP = {
  Ir: [{ family: "Inter", style: "Regular" }, false],
  Im: [{ family: "Inter", style: "Medium" }, false],
  Is: [{ family: "Inter", style: "Semi Bold" }, false],
  Ib: [{ family: "Inter", style: "Bold" }, false],
  Ii: [{ family: "Inter", style: "Italic" }, false],
  Tr: [{ family: "Inter", style: "Regular" }, true],
  Tm: [{ family: "Inter", style: "Medium" }, true],
  Ts: [{ family: "Inter", style: "Semi Bold" }, true],
  Tb: [{ family: "Inter", style: "Bold" }, true],
  Ti: [{ family: "Inter", style: "Italic" }, true],
  Sr: [{ family: "Instrument Serif", style: "Regular" }, false],
  Si: [{ family: "Instrument Serif", style: "Italic" }, false],
  Mr: [{ family: "JetBrains Mono", style: "Regular" }, false],
  Mm: [{ family: "JetBrains Mono", style: "Medium" }, false],
  Ms: [{ family: "JetBrains Mono", style: "Medium" }, false]
};

function safeFont(fontName) {
  if (loadedFontKeys.has(fontName.family + "::" + fontName.style)) return fontName;
  if (loadedFontKeys.has(fontName.family + "::Regular")) return { family: fontName.family, style: "Regular" };
  return { family: "Inter", style: "Regular" };
}

function buildStoryVariant(storyName, sTuple) {
  const [rootRect, items] = sTuple;
  const v = figma.createComponent();
  v.name = "Story=" + storyName;
  v.resize(Math.max(16, Math.round((rootRect?.[0] || 100) * 100) / 100), Math.max(16, Math.round((rootRect?.[1] || 40) * 100) / 100));
  v.fills = [];
  v.clipsContent = false;

  for (const it of items) {
    const kind = it[0];
    if (kind === 0) {
      const [, bx, by, bw, bh, bgIdx, bt, br, bb, bl, rad, shIdx, op] = it;
      if (bw <= 0 || bh <= 0) continue;
      const b = figma.createFrame();
      b.name = "box";
      b.x = bx;
      b.y = by;
      b.resize(Math.max(1, bw), Math.max(1, bh));
      b.clipsContent = false;
      b.fills = bgIdx >= 0 ? [solidPaint(STRS[bgIdx])] : [];
      if (Array.isArray(rad)) {
        b.topLeftRadius = rad[0] || 0;
        b.topRightRadius = rad[1] || 0;
        b.bottomRightRadius = rad[2] || 0;
        b.bottomLeftRadius = rad[3] || 0;
      } else if (rad > 0) {
        b.cornerRadius = rad;
      }
      const anyB = bt || br || bb || bl;
      if (anyB) {
        b.strokes = [solidPaint(STRS[anyB[2]])];
        b.strokeAlign = "INSIDE";
        if (bt && br && bb && bl && bt[0] === br[0] && br[0] === bb[0] && bb[0] === bl[0]) {
          b.strokeWeight = anyB[0];
        } else {
          b.strokeTopWeight = bt ? bt[0] : 0;
          b.strokeRightWeight = br ? br[0] : 0;
          b.strokeBottomWeight = bb ? bb[0] : 0;
          b.strokeLeftWeight = bl ? bl[0] : 0;
        }
        if (anyB[1] === 1) b.dashPattern = [4, 4];
        else if (anyB[1] === 2) b.dashPattern = [2, 2];
      }
      if (shIdx >= 0) {
        const effs = parseShadows(STRS[shIdx]);
        if (effs.length > 0) b.effects = effs;
      }
      if (op < 1) b.opacity = op;
      v.appendChild(b);
    } else if (kind === 1) {
      const [, sx, sy, sw, sh, svgIdx, op] = it;
      if (SVGS[svgIdx]) {
        try {
          const s = figma.createNodeFromSvg(SVGS[svgIdx]);
          s.name = "icon";
          s.x = sx;
          s.y = sy;
          if (sw > 0 && sh > 0 && (Math.abs(s.width - sw) > 0.5 || Math.abs(s.height - sh) > 0.5)) {
            s.resize(Math.max(1, sw), Math.max(1, sh));
          }
          if (op < 1) s.opacity = op;
          v.appendChild(s);
        } catch {}
      }
    } else if (kind === 2) {
      const [, tx, ty, tw, th, txt, fCode, fSize, lh, ls, colIdx, flags, op, lc] = it;
      const t = figma.createText();
      const [fontName, isTight] = FONT_MAP[fCode] || FONT_MAP.Ir;
      t.fontName = safeFont(fontName);
      t.fontSize = fSize || 16;
      if (lh > 0) t.lineHeight = { unit: "PIXELS", value: lh };
      let finalLs = ls;
      if (isTight && Math.abs(finalLs) < 0.05) finalLs = -0.25;
      if (finalLs !== 0) t.letterSpacing = { unit: "PIXELS", value: finalLs };
      if (flags & 1) t.textCase = "UPPER";
      if (flags & 2) t.textDecoration = "UNDERLINE";
      t.characters = String(txt ?? "");
      t.fills = [solidPaint(colIdx >= 0 ? STRS[colIdx] : "rgb(22, 20, 15)")];
      if (op < 1) t.opacity = op;
      if (lc > 1 && tw > 0) {
        t.textAutoResize = "HEIGHT";
        t.resize(Math.max(4, Math.ceil(tw + 3)), Math.max(4, Math.ceil(th)));
      } else {
        t.textAutoResize = "WIDTH_AND_HEIGHT";
      }
      t.x = tx;
      t.y = ty;
      v.appendChild(t);
    }
  }
  return v;
}

const freshNames = new Set(Object.keys(DATA).filter(k => !DATA[k][2]));
for (const child of [...page.children]) {
  if (child.type === "COMPONENT_SET" && freshNames.has(child.name)) {
    child.remove();
  } else if (child.type === "COMPONENT" && child.name.startsWith("Story=")) {
    child.remove();
  } else if (child.type === "TEXT" && freshNames.has(child.characters.trim())) {
    child.remove();
  } else if (child.type === "TEXT") {
    for (const cName of freshNames) {
      const title = DATA[cName][0];
      if (child.characters.startsWith("Validated against " + title + " ")) {
        child.remove();
        break;
      }
    }
  }
}

let yCursor = Math.max(230, ...page.children.map(n => Math.round(n.y + n.height))) + 96;
const summary = [];

for (const [compName, [title, storiesObj, isAppend, allStoryNames]] of Object.entries(DATA)) {
  const storyEntries = Object.entries(storiesObj || {});
  if (storyEntries.length === 0) continue;

  if (isAppend) {
    const existingCs = page.children.find(n => n.type === "COMPONENT_SET" && n.name === compName);
    if (existingCs) {
      let vy = Math.max(24, ...existingCs.children.map(c => Math.round(c.y + c.height))) + 28;
      let maxW = Math.max(0, ...existingCs.children.map(c => c.width));
      for (const [storyName, sTuple] of storyEntries) {
        const v = buildStoryVariant(storyName, sTuple);
        v.x = 24;
        v.y = vy;
        vy += Math.round(v.height) + 28;
        if (v.width > maxW) maxW = v.width;
        existingCs.appendChild(v);
      }
      existingCs.resize(Math.max(Math.round(maxW) + 48, 220), Math.max(vy - 4, 64));
      yCursor = Math.round(existingCs.y + existingCs.height) + 96;
      summary.push({
        component: compName,
        title,
        id: existingCs.id,
        y: existingCs.y,
        w: Math.round(existingCs.width),
        h: Math.round(existingCs.height),
        variants: existingCs.children.length
      });
      continue;
    }
  }

  const hNode = figma.createText();
  hNode.fontName = { family: "Inter", style: "Semi Bold" };
  hNode.fontSize = 40;
  hNode.lineHeight = { unit: "PIXELS", value: 46 };
  hNode.letterSpacing = { unit: "PIXELS", value: -0.8 };
  hNode.characters = compName;
  hNode.fills = [solidPaint("rgb(22, 20, 15)")];
  hNode.x = 64;
  hNode.y = yCursor;
  page.appendChild(hNode);

  const fullList = allStoryNames || storyEntries.map(([k]) => k);
  const subNode = figma.createText();
  subNode.fontName = { family: "Inter", style: "Regular" };
  subNode.fontSize = 14;
  subNode.lineHeight = { unit: "PIXELS", value: 20 };
  subNode.characters = \`Validated against \${title} — \${fullList.length} canonical Storybook \${fullList.length === 1 ? "variant" : "variants"} (\${fullList.join(", ")}) measured in headless Chromium at 748px viewport.\`;
  subNode.fills = [solidPaint("rgb(98, 92, 81)")];
  subNode.x = 64;
  subNode.y = yCursor + 54;
  page.appendChild(subNode);

  const variants = [];
  let vy = 24;
  let maxW = 0;
  for (const [storyName, sTuple] of storyEntries) {
    const v = buildStoryVariant(storyName, sTuple);
    v.x = 24;
    v.y = vy;
    vy += Math.round(v.height) + 28;
    if (v.width > maxW) maxW = v.width;
    page.appendChild(v);
    variants.push(v);
  }

  const cs = figma.combineAsVariants(variants, page);
  cs.name = compName;
  cs.x = 64;
  cs.y = yCursor + 94;
  cs.resize(Math.max(Math.round(maxW) + 48, 220), Math.max(vy - 4, 64));
  cs.fills = [{ type: "SOLID", color: { r: 0.992, g: 0.984, b: 0.969 }, opacity: 1 }];
  cs.strokes = [{ type: "SOLID", color: { r: 0.592, g: 0.278, b: 0.855 }, opacity: 0.45 }];
  cs.strokeWeight = 1.5;
  cs.dashPattern = [6, 4];
  cs.cornerRadius = 8;
  cs.clipsContent = false;

  yCursor = Math.round(cs.y + cs.height) + 96;
  summary.push({
    component: compName,
    title,
    id: cs.id,
    y: cs.y,
    w: Math.round(cs.width),
    h: Math.round(cs.height),
    variants: variants.length
  });
}

return summary;
`;
}

export function compileMeasuredToFiles(measured, outPath, pageId = '52:2') {
  for (let p = 2; p <= 50; p++) {
    const pf = outPath.replace(/\.js$/, `.part${p}.js`);
    if (pf !== outPath && fs.existsSync(pf)) fs.unlinkSync(pf);
  }

  const fullScript = buildScriptForSubset(measured, pageId);
  if (fullScript.length <= 46000) {
    fs.writeFileSync(outPath, fullScript);
    return [outPath];
  }

  const rawEntries = Object.entries(measured);
  const expandedUnits = [];
  for (const [k, v] of rawEntries) {
    if (buildScriptForSubset({ [k]: v }, pageId).length <= 46000) {
      expandedUnits.push([k, v]);
    } else {
      const allStoryNames = Object.keys(v.stories || {});
      const sEntries = Object.entries(v.stories || {});
      let curStories = {};
      let isFirst = true;
      for (const [sk, sv] of sEntries) {
        const nextStories = { ...curStories, [sk]: sv };
        const testSub = { [k]: { title: v.title, stories: nextStories, append: !isFirst, allStoryNames } };
        if (buildScriptForSubset(testSub, pageId).length > 45000 && Object.keys(curStories).length > 0) {
          expandedUnits.push([k, { title: v.title, stories: curStories, append: !isFirst, allStoryNames }]);
          isFirst = false;
          curStories = { [sk]: sv };
        } else {
          curStories = nextStories;
        }
      }
      if (Object.keys(curStories).length > 0) {
        expandedUnits.push([k, { title: v.title, stories: curStories, append: !isFirst, allStoryNames }]);
      }
    }
  }

  const chunks = [];
  let current = {};
  for (const [k, v] of expandedUnits) {
    if (k in current) {
      chunks.push(current);
      current = { [k]: v };
      continue;
    }
    const next = { ...current, [k]: v };
    const candidate = buildScriptForSubset(next, pageId);
    if (candidate.length > 46000 && Object.keys(current).length > 0) {
      chunks.push(current);
      current = { [k]: v };
    } else {
      current = next;
    }
  }
  if (Object.keys(current).length > 0) chunks.push(current);

  const writtenPaths = [];
  chunks.forEach((chunk, idx) => {
    const partPath = idx === 0 ? outPath : outPath.replace(/\.js$/, `.part${idx + 1}.js`);
    const code = buildScriptForSubset(chunk, pageId);
    fs.writeFileSync(partPath, code);
    writtenPaths.push(partPath);
  });
  return writtenPaths;
}

function runSelfTest() {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'compile-figma-selftest-'));
  const outJs = path.join(tmpDir, 'build-test.js');
  const synthetic = {};
  for (let c = 1; c <= 12; c++) {
    const stories = {};
    for (let s = 1; s <= 6; s++) {
      stories[`Variant ${s}`] = {
        key: `Variant${s}`,
        rootRect: [320, 120],
        items: Array.from({ length: 20 }, (_, idx) => ({
          kind: idx % 2 === 0 ? 'box' : 'text',
          rect: [8, idx * 6, 300, 20],
          bg: 'rgb(250, 246, 238)',
          text: `Sample text item ${c}-${s}-${idx} with realistic length`,
          fontFamily: 'Inter',
          fontSize: 14,
          fontWeight: 500,
          lineHeight: '20px',
          color: 'rgb(22, 20, 15)',
        })),
      };
    }
    synthetic[`Comp${c}`] = { title: `Test/Comp${c}`, stories };
  }

  const files = compileMeasuredToFiles(synthetic, outJs, '52:2');
  if (files.length < 2) {
    throw new Error(`Expected multi-part split for large payload, got ${files.length} file(s)`);
  }
  for (const f of files) {
    const len = fs.readFileSync(f, 'utf8').length;
    if (len > 46000) throw new Error(`File ${f} exceeded 46,000 chars (${len})`);
  }
  fs.rmSync(tmpDir, { recursive: true, force: true });
  console.log(`PASS: compile-to-figma.mjs --self-test split large fixture into ${files.length} valid <46KB parts.`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  if (args.includes('--self-test')) {
    runSelfTest();
    process.exit(0);
  }
  const inPath = args[0] || '/tmp/measured-stories.json';
  const outPath = args[1] || '/tmp/build-figma-batch.js';
  const pageIdx = args.indexOf('--page');
  const pageId = pageIdx >= 0 && args[pageIdx + 1] ? args[pageIdx + 1] : '52:2';

  const measured = JSON.parse(fs.readFileSync(inPath, 'utf8'));
  const files = compileMeasuredToFiles(measured, outPath, pageId);
  console.log(`Compiled ${Object.keys(measured).length} component(s) into ${files.length} script part(s):`);
  for (const f of files) {
    console.log(`  ${f} (${fs.readFileSync(f, 'utf8').length} chars)`);
  }
}
